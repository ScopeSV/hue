const red = @import("colors/red.zig");
const pink = @import("colors/pink.zig");

pub const Color = enum {
    red,
    red50,
    red100,
    red200,
    red300,
    red400,
    red500,
    red600,
    red700,
    red800,
    red900,
    redA100,
    redA200,
    redA400,
    redA700,

    pink,
    pink50,
    pink100,
    pink200,
    pink300,
    pink400,
    pink500,
    pink600,
    pink700,
    pink800,
    pink900,
    pinkA100,
    pinkA200,
    pinkA400,
    pinkA700,

    pub fn code(self: Color) []const u8 {
        return switch (self) {
            .red => red.@"500",
            .red50 => red.@"50",
            .red100 => red.@"100",
            .red200 => red.@"200",
            .red300 => red.@"300",
            .red400 => red.@"400",
            .red500 => red.@"500",
            .red600 => red.@"600",
            .red700 => red.@"700",
            .red800 => red.@"800",
            .red900 => red.@"900",
            .redA100 => red.A100,
            .redA200 => red.A200,
            .redA400 => red.A400,
            .redA700 => red.A700,

            .pink => pink.@"500",
            .pink50 => pink.@"50",
            .pink100 => pink.@"100",
            .pink200 => pink.@"200",
            .pink300 => pink.@"300",
            .pink400 => pink.@"400",
            .pink500 => pink.@"500",
            .pink600 => pink.@"600",
            .pink700 => pink.@"700",
            .pink800 => pink.@"800",
            .pink900 => pink.@"900",
            .pinkA100 => pink.A100,
            .pinkA200 => pink.A200,
            .pinkA400 => pink.A400,
            .pinkA700 => pink.A700,
        };
    }
};
